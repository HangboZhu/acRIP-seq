#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Build an acRIP-seq pipeline config.yaml from downloaded_complete_pairs.tsv.

Only complete IP/Input pairs are used. Pairs are grouped for joint peak
calling by stripping a trailing ".repN" from pair_id, so replicates of the
same condition end up in the same sample_pairs entry.

Example (trial subset):
  python3 make_config_from_pairs.py \
    --pairs-tsv ../4/data/metadata/downloaded_complete_pairs.tsv \
    --pair-ids GSE288115.HepAD38.WT.rep1,GSE288115.HepAD38.WT.rep2,GSE288115.HepAD38.WT.rep3 \
    --output config.trial.yaml --outputdir ./result_trial --threads 8
"""

import argparse
import csv
import json
import re
from pathlib import Path


def q(value):
    return json.dumps(str(value), ensure_ascii=False)


def split_fastq(value):
    return [x.strip() for x in str(value).split(";") if x.strip()]


def main():
    ap = argparse.ArgumentParser(description="Generate acRIP-seq config.yaml from complete pairs")
    ap.add_argument("--pairs-tsv", required=True, help="downloaded_complete_pairs.tsv")
    ap.add_argument("--pair-ids", default="", help="Comma-separated pair_id subset")
    ap.add_argument("--gse", default="", help="Restrict to one GSE")
    ap.add_argument("--output", required=True, help="Output config.yaml")
    ap.add_argument("--outputdir", default="./result", help="Pipeline output directory")
    ap.add_argument("--referencedir", default="References/hg38_chr_star_index")
    ap.add_argument("--gtf", default="References/gencode.v46.annotation.gtf")
    ap.add_argument("--genome-fasta", default="References/GRCh38.p14.genome.fa")
    ap.add_argument("--sif", default="Containers/MeRIPseq_hg38_final.sif")
    ap.add_argument("--threads", type=int, default=8)
    ap.add_argument("--genome", default="hg38")
    ap.add_argument("--p-cutoff", default="1e-10")
    ap.add_argument("--strandness", default="unstrand")
    ap.add_argument("--mapq-filter", type=int, default=255)
    ap.add_argument("--no-require-proper-pair", action="store_true")
    ap.add_argument("--skip-motif", action="store_true", default=True)
    args = ap.parse_args()

    rows = list(csv.DictReader(open(args.pairs_tsv), delimiter="\t"))
    if args.pair_ids:
        wanted = {x.strip() for x in args.pair_ids.split(",") if x.strip()}
        missing = wanted - {r["pair_id"] for r in rows}
        if missing:
            raise SystemExit(f"pair_id not found in {args.pairs_tsv}: {sorted(missing)}")
        rows = [r for r in rows if r["pair_id"] in wanted]
    if args.gse:
        rows = [r for r in rows if r["GSE"] == args.gse]
    if not rows:
        raise SystemExit("No pairs selected.")

    groups = {}
    for r in rows:
        group = re.sub(r"\.rep\d+$", "", r["pair_id"])
        groups.setdefault(group, []).append(r)

    lines = []
    lines.append("# Auto-generated by make_config_from_pairs.py")
    lines.append("# Only complete IP/Input pairs from downloaded_complete_pairs.tsv are used.")
    lines.append("sample_pairs:")
    for group in sorted(groups):
        members = sorted(groups[group], key=lambda x: x["pair_id"])
        lines.append(f"  - pair_name: {q(group)}")
        lines.append("    ip_samples:")
        for r in members:
            lines.append(f"      - {q(r['pair_id'] + '.IP')}")
        lines.append("    input_samples:")
        for r in members:
            lines.append(f"      - {q(r['pair_id'] + '.Input')}")
        lines.append("    ip_fastq:")
        for r in members:
            fqs = split_fastq(r["IP_fastq"])
            lines.append("      - " + json.dumps(fqs, ensure_ascii=False))
        lines.append("    input_fastq:")
        for r in members:
            fqs = split_fastq(r["Input_fastq"])
            lines.append("      - " + json.dumps(fqs, ensure_ascii=False))

    lines.extend([
        "",
        f"outputdir: {q(args.outputdir)}",
        f"referencedir: {q(args.referencedir)}",
        f"gtf: {q(args.gtf)}",
        f"genome_fasta: {q(args.genome_fasta)}",
        f"sif: {q(args.sif)}",
        "",
        f"threads: {args.threads}",
        f"genome: {q(args.genome)}",
        f"strandness: {q(args.strandness)}",
        f"p_cutoff: {args.p_cutoff}",
        "fragment_length: 100",
        "bin_size: 25",
        "step_size: 25",
        'star_extra_args: ""',
        f"mapq_filter: {args.mapq_filter}",
        f"require_proper_pair: {'False' if args.no_require_proper_pair else 'True'}",
        "",
        "skip_peak: False",
        f"skip_motif: {'True' if args.skip_motif else 'False'}",
        "scan_motif_pvalue: 0.01",
        'scan_motif: "References/ac4C.meme"',
        "liftover: False",
        'liftover_chain: ""',
        'liftover_target_fasta: ""',
        "",
    ])

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out}")
    print(f"Groups: {len(groups)}; pairs: {len(rows)}")
    for group in sorted(groups):
        print(f"  {group}: {len(groups[group])} pair(s)")


if __name__ == "__main__":
    main()
